"""E2: validate the robustness battery on NegEx/ConText, where the correct effect of each perturbation is known.

Rules set before any run (see docs/EXPERIMENT_PLAN.md):
Sample (seed 13, from the 2,376 labelled mentions): 120 Negated, 120 Affirmed+Recent, 80 Affirmed+Historical, 40 Affirmed+Not particular
  (Not particular has 56 in all, so it is taken whole if smaller), 360 mentions. Stratified so rare labels have enough cases.
Perturbations (sweetspot/perturb.py): negate, paraphrase, reorder, distractor; generated by the model, kept only if the NLI check accepts
  and the concept words survive. Expected labels: negate flips negation and keeps temporality and experiencer; the others change nothing.
Arms, unchanged from the saved open benchmark: status (status record + the fixed mapping), direct (asks the three labels), context
  (medspaCy ConText rules; reference only, it is rule-based).
Scores per arm and perturbation:
  labelled   accuracy of all three labels against the expected labels (exact match on negation, temporality, experiencer);
  label-free consistency with the arm's own answer on the original: for negate, negation must differ and the other two must match;
             for the rest, all three must match. Uses no gold labels.
D4: the label-free score is used on MIMIC if, pooled over perturbations, it orders the three arms as labelled accuracy does
  (identical ranking), and per perturbation the Kendall tau is reported.
Outputs: results/sweetspot/e2_negex_battery.json (counts, scores, costs; NegEx text is public but only ids are kept).
"""
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
import modal_open_bench as M  # noqa: E402
from mds_pilot.reader import STATUS_SCHEMA, SYSTEM, build_prompt  # noqa: E402
from sweetspot import perturb  # noqa: E402
from sweetspot.llm import LLM, cost  # noqa: E402

OUT = ROOT / "results/sweetspot/e2_negex_battery.json"
STRATA = [("Negated", None, 120), ("Affirmed", "Recent", 120), ("Affirmed", "Historical", 80), ("Affirmed", "Not particular", 40)]
LABELS = ("negation", "temporality", "experiencer")


def sample(rows):
    rng = random.Random(13)
    out = []
    for neg, temp, n in STRATA:
        pool = [r for r in rows if r["negation"] == neg and (temp is None or r["temporality"] == temp)]
        out += rng.sample(pool, min(n, len(pool)))
    return out


def arm_requests(arm, items):
    reqs = []
    for it in items:
        if arm == "status":
            prompt = build_prompt("status", f"the condition: {it['concept']}", [(1, "Report", it["sentence"])])
            reqs.append({"name": "status", "system": SYSTEM, "prompt": prompt, "schema": STATUS_SCHEMA})
        else:
            prompt = f"Condition: {it['concept']}\nSentence: {it['sentence']}\n\n{M.DIRECT_RULES}"
            reqs.append({"name": "context", "system": SYSTEM, "prompt": prompt, "schema": M.DIRECT_SCHEMA})
    return reqs


def to_labels(arm, parsed):
    if parsed is None:
        return None
    if arm == "status":
        ms = parsed["mentions"]
        m = ms[0] if ms else {"assertion": "affirmed", "timing": "current_stay", "subject": "patient"}
        return {"negation": "Negated" if m["assertion"] == "negated" else "Affirmed",
                "temporality": M.NEGEX_TIMING.get(m["timing"], "Recent"),
                "experiencer": "Other" if m["subject"] == "other_person" else "Patient"}
    return {"negation": parsed["negation"], "temporality": "Not particular" if parsed["temporality"] == "Hypothetical" else parsed["temporality"],
            "experiencer": parsed["experiencer"]}


def context_labels(items):
    import medspacy
    nlp = medspacy.load()
    ctx = nlp.get_pipe("medspacy_context")
    out = []
    for it in items:
        doc = nlp.make_doc(it["sentence"])
        for i, token in enumerate(doc):  # each item is one sentence, as in the saved ConText arm
            token.is_sent_start = i == 0
        span = M.concept_span(it["sentence"], it["concept"])
        ent = doc.char_span(*span, label="CONDITION", alignment_mode="expand") if span else None
        if ent is None:
            out.append({"negation": "Affirmed", "temporality": "Recent", "experiencer": "Patient"})
            continue
        doc.ents = [ent]
        ctx(doc)
        e = doc.ents[0]
        out.append({"negation": "Negated" if e._.is_negated else "Affirmed",
                    "temporality": "Historical" if e._.is_historical else "Not particular" if e._.is_hypothetical else "Recent",
                    "experiencer": "Other" if e._.is_family else "Patient"})
    return out


def expected(gold, kind):
    e = dict(gold)
    if kind == "negate":
        e["negation"] = "Affirmed" if gold["negation"] == "Negated" else "Negated"
    return e


def consistent(orig, pert, kind):
    if orig is None or pert is None:
        return None
    if kind == "negate":
        return pert["negation"] != orig["negation"] and all(pert[k] == orig[k] for k in ("temporality", "experiencer"))
    return all(pert[k] == orig[k] for k in LABELS)


def kendall(a, b):
    keys = list(a)
    s = 0
    pairs = 0
    for i in range(len(keys)):
        for j in range(i + 1, len(keys)):
            x, y = a[keys[i]] - a[keys[j]], b[keys[i]] - b[keys[j]]
            if x and y:
                s += 1 if (x > 0) == (y > 0) else -1
            pairs += 1
    return s / pairs if pairs else None


def main():
    rows = M.negex_rows()
    items = sample(rows)
    gen = LLM("e2_rewrites")
    nli = perturb.NLI()
    variants, generation = {"original": items}, {}
    for kind in perturb.KINDS:
        replies = gen.run(perturb.requests_for(items, kind))
        texts = [r["parsed"]["text"].strip() if r else None for r in replies]
        cand = [(it, t) for it, t in zip(items, texts) if t and perturb.contains_concept(t, it["concept"]) and t != it["sentence"]]
        ok = perturb.accept(kind, nli, [c[0]["sentence"] for c in cand], [c[1] for c in cand]) if cand else []
        variants[kind] = [{**it, "sentence": t} for (it, t), good in zip(cand, ok) if good]
        generation[kind] = {"generated": len(items), "kept_concept": len(cand), "accepted_by_nli": len(variants[kind]), **cost(replies)}
    preds, arm_cost = {}, {}
    for arm in ("status", "direct", "context"):
        preds[arm] = {}
        rows_used = []
        for kind, its in variants.items():
            if arm == "context":
                preds[arm][kind] = dict(zip([i["id"] for i in its], context_labels(its)))
            else:
                llm = LLM(f"e2_{arm}")
                replies = llm.run(arm_requests(arm, its))
                rows_used += replies
                preds[arm][kind] = {i["id"]: to_labels(arm, r["parsed"] if r else None) for i, r in zip(its, replies)}
        arm_cost[arm] = cost(rows_used) if rows_used else {"usd": 0.0, "calls": 0}
    gold = {r["id"]: {k: r[k] for k in LABELS} for r in items}
    scores = {}
    for arm in preds:
        scores[arm] = {}
        orig = preds[arm]["original"]
        acc_o = [all(orig[i][k] == gold[i][k] for k in LABELS) for i in orig if orig[i]]
        scores[arm]["original"] = {"n": len(acc_o), "labelled_accuracy": round(sum(acc_o) / len(acc_o), 4)}
        pooled_l, pooled_f = [], []
        for kind in perturb.KINDS:
            p = preds[arm][kind]
            lab = [all(p[i][k] == expected(gold[i], kind)[k] for k in LABELS) for i in p if p[i]]
            free = [c for c in (consistent(orig.get(i), p[i], kind) for i in p) if c is not None]
            pooled_l += lab
            pooled_f += free
            scores[arm][kind] = {"n": len(lab), "labelled_accuracy": round(sum(lab) / len(lab), 4),
                                 "label_free_consistency": round(sum(free) / len(free), 4)}
        scores[arm]["pooled"] = {"labelled_accuracy": round(sum(pooled_l) / len(pooled_l), 4),
                                 "label_free_consistency": round(sum(pooled_f) / len(pooled_f), 4)}
    rank = lambda key, kind: {a: scores[a][kind][key] for a in scores}
    d4 = {kind: kendall(rank("labelled_accuracy", kind), rank("label_free_consistency", kind)) for kind in (*perturb.KINDS, "pooled")}
    order = lambda d: sorted(d, key=d.get, reverse=True)
    result = {"sample": {f"{n}/{t}": c for n, t, c in STRATA}, "mentions": len(items), "generation": generation,
              "scores": scores, "cost": arm_cost,
              "D4": {"kendall_tau_by_perturbation": d4,
                     "order_labelled": order(rank("labelled_accuracy", "pooled")),
                     "order_label_free": order(rank("label_free_consistency", "pooled")),
                     "holds": order(rank("labelled_accuracy", "pooled")) == order(rank("label_free_consistency", "pooled"))}}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(result, indent=1))
    print(json.dumps(result, indent=1))


if __name__ == "__main__":
    main()
